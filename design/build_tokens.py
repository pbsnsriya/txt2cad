"""Generate the frontend token CSS from tokens.json (light) and tokens.dark.json.

Run:  python design/build_tokens.py
Writes frontend/src/styles/tokens.css (custom properties that switch with the theme) and theme.css (the Tailwind v4 mapping, so
utilities such as bg-surface, text-fg and border-border follow the theme).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "frontend" / "src" / "styles"
L = json.loads((HERE / "tokens.json").read_text(encoding="utf-8"))
D = json.loads((HERE / "tokens.dark.json").read_text(encoding="utf-8"))


def cv(c):
    return "\n".join(f"  --tk-{k}: {v};" for k, v in c.items())


dark_extra = "  --tk-shadow-card: 0 1px 2px rgba(0,0,0,.4);\n  --tk-shadow-pop: 0 12px 32px rgba(0,0,0,.5);\n  color-scheme: dark;"
css = ["/* Generated by design/build_tokens.py from design/tokens*.json. Edit the JSON, not this file. */",
       ":root {", cv(L["color"]),
       f"  --tk-shadow-card: {L['shadow']['card']};", f"  --tk-shadow-pop: {L['shadow']['pop']};",
       "  color-scheme: light;", "}",
       ":root[data-theme=\"dark\"] {", cv(D["color"]), dark_extra, "}",
       "@media (prefers-color-scheme: dark) {", "  :root:not([data-theme=\"light\"]) {",
       "\n".join("  " + line for line in cv(D["color"]).split("\n")),
       "\n".join("  " + line for line in dark_extra.split("\n")), "  }", "}"]
(OUT / "tokens.css").write_text("\n".join(css) + "\n", encoding="utf-8")

ALIAS = {"text": "fg", "text-muted": "muted", "border-input": "input"}   # so utilities read text-fg, text-muted, border-input
tw = ["/* Tailwind v4 mapping. Generated by design/build_tokens.py. Components use bg-surface, text-muted, border-border; never raw hex. */",
      "@theme inline {"]
tw += [f"  --color-{ALIAS.get(n, n)}: var(--tk-{n});" for n in L["color"]]
tw += ["  --shadow-card: var(--tk-shadow-card);", "  --shadow-pop: var(--tk-shadow-pop);", "}", "@theme {",
       f"  --font-sans: {L['font']['sans']};", f"  --font-mono: {L['font']['mono']};"]
for k, v in L["type"].items():
    tw += [f"  --text-{k}: {v['size'] / 16}rem;", f"  --text-{k}--line-height: {v['line'] / v['size']:.4f};", f"  --text-{k}--font-weight: {v['weight']};"]
tw += [f"  --radius-{k}: {v}px;" for k, v in L["radius"].items()]
tw += [f"  --ease-app: {L['motion']['ease']};", f"  --duration-fast: {L['motion']['fast']};", f"  --duration-base: {L['motion']['base']};", "}"]
(OUT / "theme.css").write_text("\n".join(tw) + "\n", encoding="utf-8")
print("written to", OUT)
